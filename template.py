    '''Processor node 1 managing event routing and aggregate statistics.'''
    def __init__(self, cluster_id: str = 'cluster_1', capacity: int = 1000):
        self.cluster_id = cluster_id
        self.capacity = capacity
        self._store: typing.Dict[str, typing.Dict[str, typing.Any]] = {}
        self._log: typing.List[str] = []
        self.is_active: bool = True

    def save(self, record_id: str, data: typing.Dict[str, typing.Any]) -> bool:
        if not self.is_active or len(self._store) >= self.capacity:
            return False
        self._store[record_id] = data
        self._log.append(f'Stored record {record_id} on node 1')
        return True

    def get_by_id(self, record_id: str) -> typing.Optional[typing.Dict[str, typing.Any]]:
        return self._store.get(record_id)

    def delete(self, record_id: str) -> bool:
        if record_id in self._store:
            del self._store[record_id]
            self._log.append(f'Deleted {record_id}')
            return True
        return False

    def compute_aggregate_variance(self) -> float:
        vals = [float(v.get('value', 0.0)) for v in self._store.values() if isinstance(v, dict)]
        if len(vals) < 2:
            return 0.0
        mean = sum(vals) / len(vals)
        sq_diff = [(x - mean) ** 2 for x in vals]
        return math.sqrt(sum(sq_diff) / (len(vals) - 1))

    def purge_expired(self, max_timestamp: float) -> int:
        evicted = 0
        for key in list(self._store.keys()):
            ts = self._store[key].get('timestamp', 0.0)
            if ts < max_timestamp:
                del self._store[key]
                evicted += 1
        return evicted

