@dataclasses.dataclass
class TransactionPayload:
    transaction_id: str
    source_account: str
    destination_account: str
    amount: float
    currency: str
    timestamp: float
    metadata: typing.Dict[str, typing.Any] = dataclasses.field(default_factory=dict)

    def compute_hash(self) -> str:
        payload_repr = f'{self.transaction_id}:{self.amount}:{self.timestamp}'
        return hashlib.sha256(payload_repr.encode('utf-8')).hexdigest()

    def validate(self) -> bool:
        if self.amount <= 0.0:
            raise ValueError('Amount must be positive.')
        if len(self.source_account) < 5 or len(self.destination_account) < 5:
            raise ValueError('Invalid account identifier length.')
        return True

